#!/usr/bin/env python3
"""
Quick script to upload a published ebook package to Gumroad.
Requires: requests, getpass
Usage: python monetize_gumroad.py <book_id>
The script will ask for your Gumroad access token (not stored).
It will upload the .gumroad.zip file created by the ebook engine.
"""

import getpass
import os
import sys
from pathlib import Path

# Add the project root to sys.path so we can import ebook_engine modules
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from ebook_engine.catalog import get_book


def main():
    if len(sys.argv) < 2:
        print("Usage: python monetize_gumroad.py <book_id>")
        sys.exit(1)

    try:
        book_id = int(sys.argv[1])
    except ValueError:
        print("Book ID must be an integer")
        sys.exit(1)

    book = get_book(book_id)
    if not book:
        print(f"Book ID {book_id} not found in catalog")
        sys.exit(1)

    title = book.get("title", "Unknown")
    gumroad_path = book.get("file_gumroad")
    if not gumroad_path or not os.path.isfile(gumroad_path):
        print(f"No Gumroad package found for book {book_id}. Run 'publish' first.")
        sys.exit(1)

    zip_path = Path(gumroad_path)
    print(f"Found Gumroad package: {zip_path}")
    print(f"Size: {zip_path.stat().st_size / 1024:.1f} KB")

    # Ask for Gumroad token
    token = getpass.getpass("Enter your Gumroad access token (input hidden): ").strip()
    if not token:
        print("No token provided. Aborting.")
        sys.exit(1)

    # Gumroad API endpoint for product creation
    url = "https://api.gumroad.com/v2/products"
    # We'll create a simple product: name = title, price = suggested price from config
    # For simplicity, we'll set price in USD (convert from INR config roughly)
    from ebook_engine.config import PRICING

    tier = book.get("price_tier", "basic")
    price_inr = PRICING.get(tier, PRICING["basic"])["price_inr"]
    # Rough conversion: 1 USD = 83 INR (as of 2026, adjust if needed)
    price_usd = max(1, round(price_inr / 83, 2))
    print(f"Setting price to ${price_usd} (based on ₹{price_inr})")

    # Prepare the multipart/form-data
    files = {"file": (zip_path.name, open(zip_path, "rb"), "application/zip")}
    data = {
        "access_token": token,
        "name": title,
        "price": str(price_usd),
        "description": (
            f"Ebook generated by Hermes Ebook Engine.\n\n"
            f"Book ID: {book_id}\n"
            f"Genre: {book.get('genre', 'N/A')}\n"
            f"Chapters: {len(book.get('chapters')) if book.get('chapters') else 'N/A'}"
        ),
        "custom_permalink": f"ebook-engine-{book_id}",
    }

    print("Uploading to Gumroad...")
    try:
        import requests

        resp = requests.post(url, data=data, files=files)
        resp.raise_for_status()
        result = resp.json()
        if result.get("success"):
            product_url = result.get("product", {}).get("short_url")
            print(f"\nSuccess! Product created: {product_url}")
            print(f"Edit URL: https://gumroad.com/products/{result.get('product', {}).get('id')}")
            print("\nNext steps:")
            print("1. Share the product URL to start selling.")
            print("2. Consider adding a cover image via Gumroad dashboard.")
            print("3. Enable 'Send email receipts' and set up payouts.")
        else:
            print(f"Gumroad returned error: {result.get('error_message')}")
    except requests.exceptions.RequestException as e:
        print(f"Request failed: {e}")
        sys.exit(1)
    finally:
        files["file"][1].close()


if __name__ == "__main__":
    main()
