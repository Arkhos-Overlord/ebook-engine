"""Path/filename sanitisation helpers."""

import os
from pathlib import Path

from ebook_engine.paths import safe_filename as _safe_filename
from ebook_engine.paths import slug as _slug


def test_slug_neutralises_path_separators():
    """A title containing '/' must never be able to write outside output/."""
    for bad in ("a/b", "a\\b", "..\\..\\evil", "/etc/passwd"):
        slug = _slug(bad)
        assert "/" not in slug
        assert "\\" not in slug
        assert not os.path.isabs(slug)


def test_slug_keeps_existing_naming_convention():
    """Preserve the on-disk names already generated by earlier batch runs."""
    assert _slug("Fitness & Nutrition") == "fitness-&-nutrition"
    assert _slug("Digital Marketing") == "digital-marketing"
    assert _slug("Meditation & Mindfulness") == "meditation-&-mindfulness"


def test_slug_never_empty():
    assert _slug("") == "untitled"
    assert _slug("   ") != ""


def test_safe_filename_strips_reserved_characters():
    for bad in ("<title>", "a:b", "a|b", "a?b", "a*b", 'a"b', "x/y"):
        name = _safe_filename(bad, ".epub")
        for ch in '<>:"/\\|?*':
            assert ch not in name, f"{bad!r} leaked {ch!r}"
        assert name.endswith(".epub")


def test_safe_filename_keeps_readable_titles():
    assert _safe_filename("Fitness & Nutrition", ".epub") == ("Fitness & Nutrition.epub")


def test_safe_filename_never_collapses_to_empty():
    assert _safe_filename("", ".epub") == "untitled.epub"
    assert _safe_filename("...", ".epub") == "untitled.epub"


class TestArtifactNaming:
    """Regression: publish and batch_generate used to name the same book
    differently (`Digital Marketing.epub` vs `digital-marketing.epub`), so
    running both left two copies of every book and the catalog pointed at
    whichever ran last. They must now agree on one path.
    """

    def test_batch_writes_to_the_shared_naming_convention(
        self, tmp_path, temp_catalog, monkeypatch
    ):
        """Regression: batch and publish named the same book differently
        (`Digital Marketing.epub` vs `digital-marketing.epub`), so running
        both left two copies of every book.

        `temp_catalog` is required, not optional: without it upsert_book
        writes to the real state/catalog.db, which is how row 7 once ended
        up pointing at a pytest temp directory.
        """
        import ebook_engine.batch_generate as batch
        from ebook_engine.paths import artifact_path

        tmp_path.mkdir(parents=True, exist_ok=True)
        monkeypatch.setattr(batch, "OUTPUT_DIR", tmp_path)

        status = batch.generate_single_book("Fitness & Nutrition")
        assert status["ok"], status

        for extension in (".epub", ".pdf", ".kdp.zip", ".gumroad.zip"):
            expected = Path(artifact_path(tmp_path, "Fitness & Nutrition", extension))
            assert expected.is_file(), expected
        # The old title-cased name must not appear alongside it.
        assert not (tmp_path / "Fitness & Nutrition.epub").exists()
        assert not (tmp_path / "Fitness & Nutrition.pdf").exists()

    def test_extension_with_or_without_a_dot(self, tmp_path):
        from ebook_engine.paths import artifact_path

        assert artifact_path(tmp_path, "Travel", ".epub") == artifact_path(
            tmp_path, "Travel", "epub"
        )

    def test_title_with_a_separator_cannot_escape_the_directory(self, tmp_path):
        from ebook_engine.paths import artifact_path

        path = Path(artifact_path(tmp_path, "../../etc/passwd", ".epub"))
        # The slug flattens separators, so the file lands in the target
        # directory rather than climbing out of it.
        assert path.parent == tmp_path
        assert "/" not in path.name
        assert "\\" not in path.name

    def test_artifacts_share_one_naming_convention(self, tmp_path):
        """One book, every artifact, one stem."""
        from ebook_engine.paths import artifact_path

        title = "Meditation & Mindfulness"
        extensions = (".epub", ".pdf", ".kdp.zip", ".gumroad.zip")
        stems = {Path(artifact_path(tmp_path, title, ext)).name[: -len(ext)] for ext in extensions}
        assert stems == {"meditation-&-mindfulness"}
